#ifndef GTA_RESOURCE_PROBE_H
#define GTA_RESOURCE_PROBE_H
typedef unsigned long long u64;
typedef unsigned int u32;
typedef void (*Forward)(void *);
typedef void *(*GetDevice)(const char *, int);
typedef int (*MountGlobal)(const char *,void *,int);
typedef void (*UnmountDevice)(void *);
typedef void (*UnmountPath)(const char *);
typedef u32 (*GetAttributes)(void *,const char *);
typedef u64 (*GetLength)(void *,const char *);
typedef u64 (*OpenBulk)(void *,const char *,u64 *);
typedef u32 (*ReadBulk)(void *,u64,u64,void *,u32);
typedef void (*CloseBulk)(void *,u64);
typedef u32 (*GetResourceVersion)(void *,const char *,u64 *);
typedef u32 (*FindSlot)(void *,const char *);
typedef u32 (*RegisterRaw)(const char *,const char *,int,int);
typedef void (*RequestObject)(u32,u32);
typedef int (*ReleaseObject)(u32);
typedef u64 (*GetPointer)(void *,u32);
typedef struct {
    u64 vtable,base;
    char root[256];
    u32 prefix_length;
    unsigned char allow_root,padding[3];
} RelativeDevice;
typedef struct {
    u64 magic,forward;
    volatile u32 state,visits;
    u64 devices[3];
    u32 error,command;
    u64 alias_before,alias_during,alias_after;
    u32 mounted,attributes_direct,attributes_alias;
    RelativeDevice relative;
    u64 file_device,file_vtable;
    u32 file_attributes,read_count;
    u64 bulk_base;
    unsigned char header[16];
    u64 file_length;
    u64 resource_flags;
    u32 resource_version,module_version,known_slot,missing_slot;
    u32 raw_before,raw_after,pool_before,pool_after;
    u32 registered_index,registered_slot,raw_registered,pool_registered;
    u64 registered_entry;
    u32 requested_index,expected_handle,phase,ticks;
    u64 before_entry,loaded_entry,loaded_pointer,after_entry,after_pointer;
    u32 request_called,release_called,release_result,loaded;
    u64 dictionary_words[8];
    u64 capture_buffer;
    u32 capture_capacity,capture_count;
    unsigned char preceding_bytes[16];
    u64 adapter_vtable[59];
    u64 worker_offset;
    u32 worker_length,worker_count;
    unsigned char worker_bytes[16];
    volatile u32 worker_seen,worker_ack;
} Probe;
_Static_assert(__builtin_offsetof(RelativeDevice,prefix_length)==0x110,"Relative device layout");
_Static_assert(__builtin_offsetof(Probe,relative)==0x60,"Probe layout");
_Static_assert(__builtin_offsetof(Probe,file_device)==0x178,"File probe layout");
_Static_assert(__builtin_offsetof(Probe,header)==0x198,"File header layout");
_Static_assert(__builtin_offsetof(Probe,resource_flags)==0x1b0,"Resource flags layout");
_Static_assert(__builtin_offsetof(Probe,registered_index)==0x1d8,"Registration layout");
_Static_assert(__builtin_offsetof(Probe,requested_index)==0x1f0,"Load input layout");
_Static_assert(__builtin_offsetof(Probe,dictionary_words)==0x238,"Loaded header layout");
_Static_assert(__builtin_offsetof(Probe,capture_buffer)==0x278,"Capture input layout");
_Static_assert(__builtin_offsetof(Probe,adapter_vtable)==0x298,"Adapter vtable layout");
_Static_assert(sizeof(Probe)==0x498,"Probe size");
#endif
